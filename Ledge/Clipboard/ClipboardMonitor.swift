import AppKit

/// 일반 페이스트보드를 0.5초마다 보고 바뀌면 알린다. 접근성 권한 불필요.
/// 비밀번호 관리자가 붙이는 숨김 표시(org.nspasteboard.ConcealedType 등)가 있으면 건너뛴다.
@MainActor
final class ClipboardMonitor {
    var onChange: ((NSPasteboard) -> Void)?

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    /// 이 타입이 실려 있으면 기록하지 않는다(비밀번호·일회성·자동 생성).
    static let skipTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("com.typeit4me.clipping"),
    ]

    var isRunning: Bool { timer != nil }

    init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        LedgeLog.write("clipboard monitor start")
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        LedgeLog.write("clipboard monitor stop")
    }

    /// 앱 자신이 페이스트보드에 쓴 직후 호출: 그 변화는 기록하지 않는다.
    func ignoreCurrentChange() {
        lastChangeCount = pasteboard.changeCount
    }

    private func tick() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        let types = pasteboard.types ?? []
        if Self.skipTypes.contains(where: types.contains) {
            LedgeLog.write("clipboard: skipped (concealed/transient)")
            return
        }
        let front = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if AppSettings.shared.isClipboardIgnored(bundleID: front) {
            LedgeLog.write("clipboard: skipped app \(front ?? "-")")
            return
        }
        onChange?(pasteboard)
    }
}
